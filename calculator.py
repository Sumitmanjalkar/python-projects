


A = int(input('Enter first number: '))
B = int(input('Enter second number: '))
C = input('Enter your operation: ')
if C == '+':
    print(A+B)
elif C == '-':
    print(A-B)

elif C =='*':
    print(A*B)

elif C =='/':
    print(A/B)

elif C == '%':
     print((A * B) / 100) 


elif C == '**':
     print(A ** B)

else : 
    print('something went wrong ')



    



